// Command compatcatalog renders the provider compatibility and task matrices
// in the public documentation from the canonical catalog in
// internal/compatcatalog. Only the text between explicit marker comments is
// replaced; the surrounding prose is left untouched.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/nkiyohara/corresync/internal/compatcatalog"
)

const issueBase = "https://github.com/nkiyohara/corresync/issues/"

// region is one generated block inside one documentation file.
type region struct {
	document string
	name     string
	render   func(compatcatalog.Catalog, string) string
}

var regions = []region{
	{document: "docs/compatibility.md", name: "evidence", render: renderEvidence},
	{document: "docs/tasks.md", name: "tasks", render: renderTasks},
}

func main() {
	check := flag.Bool("check", false, "fail when a generated documentation table is stale")
	root := flag.String("root", ".", "repository root")
	flag.Parse()

	catalog, err := compatcatalog.Default()
	if err != nil {
		fail(err)
	}
	stale, err := apply(catalog, *root, !*check)
	if err != nil {
		fail(err)
	}
	if *check && len(stale) > 0 {
		fail(fmt.Errorf("generated compatibility tables are stale in %s; run task docs:generate",
			strings.Join(stale, ", ")))
	}
}

// apply renders every region and returns the documents whose content differs.
// It writes the documents only when write is true.
func apply(catalog compatcatalog.Catalog, root string, write bool) ([]string, error) {
	contents := make(map[string][]byte)
	var order []string
	for _, item := range regions {
		current, ok := contents[item.document]
		if !ok {
			data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(item.document))) // #nosec G304 -- repository-owned documentation path.
			if err != nil {
				return nil, fmt.Errorf("read %s: %w", item.document, err)
			}
			current = data
			order = append(order, item.document)
		}
		prefix := relativePrefix(item.document)
		updated, err := replaceRegion(current, item.name, item.render(catalog, prefix))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", item.document, err)
		}
		contents[item.document] = updated
	}
	var stale []string
	for _, document := range order {
		target := filepath.Join(root, filepath.FromSlash(document))
		existing, err := os.ReadFile(target) // #nosec G304 -- repository-owned documentation path.
		if err != nil {
			return nil, err
		}
		if bytes.Equal(existing, contents[document]) {
			continue
		}
		stale = append(stale, document)
		if write {
			if err := os.WriteFile(target, contents[document], 0o644); err != nil { // #nosec G306 -- public documentation.
				return nil, fmt.Errorf("write %s: %w", document, err)
			}
		}
	}
	return stale, nil
}

func beginMarker(name string) string {
	return "<!-- compatcatalog:begin " + name + " -->"
}

func endMarker(name string) string {
	return "<!-- compatcatalog:end " + name + " -->"
}

// replaceRegion replaces the lines strictly between one begin marker line and
// its matching end marker line.
func replaceRegion(document []byte, name, generated string) ([]byte, error) {
	text := string(document)
	begin, end := beginMarker(name)+"\n", endMarker(name)+"\n"
	if strings.Count(text, begin) != 1 || strings.Count(text, end) != 1 {
		return nil, fmt.Errorf("want exactly one %q and one %q marker line", beginMarker(name), endMarker(name))
	}
	start := strings.Index(text, begin)
	stop := strings.Index(text, end)
	if stop < start || (start > 0 && text[start-1] != '\n') || text[stop-1] != '\n' {
		return nil, errors.New("generated region markers are out of order or not on their own lines")
	}
	return []byte(text[:start+len(begin)] + generated + text[stop:]), nil
}

// relativePrefix is the link prefix from a document to the repository root.
func relativePrefix(document string) string {
	depth := strings.Count(path.Dir(document), "/") + 1
	if path.Dir(document) == "." {
		depth = 0
	}
	return strings.Repeat("../", depth)
}

const (
	lintDisable = "<!-- markdownlint-disable MD013 -->\n"
	lintEnable  = "<!-- markdownlint-enable MD013 -->\n"
)

const generatedNotice = "<!-- Generated by tools/compatcatalog from internal/compatcatalog/catalog.json; do not edit by hand. -->\n"

func renderEvidence(catalog compatcatalog.Catalog, prefix string) string {
	var document strings.Builder
	document.WriteString(lintDisable + generatedNotice)
	document.WriteString("\nAvailability means what you can do in the current source:\n\n")
	for _, value := range compatcatalog.Availabilities() {
		_, _ = fmt.Fprintf(&document, "- `%s`: %s.\n", value, value.Description())
	}
	document.WriteString("\nLive evidence states:\n\n")
	for _, value := range compatcatalog.LiveStates() {
		_, _ = fmt.Fprintf(&document, "- `%s`: %s.\n", value, value.Description())
	}
	document.WriteString("\nAuthentication kinds:\n\n")
	for _, value := range compatcatalog.Authentications() {
		_, _ = fmt.Fprintf(&document, "- `%s`: %s.\n", value, value.Description())
	}
	for _, service := range compatcatalog.Services() {
		entries := filter(catalog, service)
		if len(entries) == 0 {
			continue
		}
		_, _ = fmt.Fprintf(&document, "\n### %s\n\n", serviceTitle(service))
		if service == compatcatalog.ServiceBoundary {
			document.WriteString("| Boundary | Availability | Deterministic evidence | Live evidence | Notes | Issue |\n")
			document.WriteString("| --- | --- | --- | --- | --- | --- |\n")
			for _, entry := range entries {
				_, _ = fmt.Fprintf(&document, "| %s | `%s` | %s | %s | %s | %s |\n",
					entry.ProviderName, entry.Availability, deterministic(entry, prefix),
					live(entry, prefix), orDash(entry.Notes), issue(entry.Issue))
			}
		} else {
			document.WriteString("| Provider | Route | Availability | Authentication | Deterministic evidence | Live evidence | Notes | Issue |\n")
			document.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- |\n")
			for _, entry := range entries {
				_, _ = fmt.Fprintf(&document, "| %s (`%s`) | `%s` | `%s` | `%s` | %s | %s | %s | %s |\n",
					entry.ProviderName, entry.Provider, entry.Route, entry.Availability,
					entry.Authentication, deterministic(entry, prefix), live(entry, prefix),
					orDash(entry.Notes), issue(entry.Issue))
			}
		}
	}
	document.WriteString(lintEnable)
	return document.String()
}

func renderTasks(catalog compatcatalog.Catalog, prefix string) string {
	var document strings.Builder
	document.WriteString(lintDisable + generatedNotice)
	document.WriteString("| Provider route | Availability | CRUD/state | Reminder/recurrence | Hierarchy/metadata | Time contract | Sync candidate | Live evidence | Evidence issue |\n")
	document.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
	for _, entry := range filter(catalog, compatcatalog.ServiceTasks) {
		contract := entry.TaskContract
		_, _ = fmt.Fprintf(&document, "| `%s` | `%s` | %s | %s | %s | %s | %s | %s | %s |\n",
			entry.Provider, entry.Availability, contract.CRUDState, contract.ReminderRecurrence,
			contract.HierarchyMetadata, contract.TimeContract, contract.Sync,
			live(entry, prefix), issue(entry.Issue))
	}
	document.WriteString(lintEnable)
	return document.String()
}

func filter(catalog compatcatalog.Catalog, service compatcatalog.Service) []compatcatalog.Entry {
	var entries []compatcatalog.Entry
	for _, entry := range catalog.Entries {
		if entry.Service == service {
			entries = append(entries, entry)
		}
	}
	return entries
}

func serviceTitle(service compatcatalog.Service) string {
	switch service {
	case compatcatalog.ServiceMail:
		return "Mail"
	case compatcatalog.ServiceCalendar:
		return "Calendar"
	case compatcatalog.ServiceTasks:
		return "Tasks"
	case compatcatalog.ServiceMessages:
		return "Messages"
	case compatcatalog.ServiceBoundary:
		return "Product boundaries"
	default:
		return string(service)
	}
}

func deterministic(entry compatcatalog.Entry, prefix string) string {
	if len(entry.Deterministic.Tests) == 0 {
		return entry.Deterministic.Summary
	}
	links := make([]string, len(entry.Deterministic.Tests))
	for index, test := range entry.Deterministic.Tests {
		links[index] = fmt.Sprintf("[`%s`](%s%s)", test, prefix, test)
	}
	return entry.Deterministic.Summary + "; tests: " + strings.Join(links, ", ")
}

func live(entry compatcatalog.Entry, prefix string) string {
	text := fmt.Sprintf("`%s`: %s", entry.Live.State, entry.Live.Summary)
	if entry.Live.Record != "" {
		text += fmt.Sprintf(" ([record](%s%s))", prefix, entry.Live.Record)
	}
	return text
}

func issue(number int) string {
	if number == 0 {
		return "—"
	}
	value := strconv.Itoa(number)
	return "[#" + value + "](" + issueBase + value + ")"
}

func orDash(value string) string {
	if value == "" {
		return "—"
	}
	return value
}

func fail(err error) {
	_, _ = fmt.Fprintln(os.Stderr, "compatcatalog:", err)
	os.Exit(1)
}
